// Read non-secret config from gradle.properties (or a local.properties override).
// NOTE: This is where PUBLIC config (backend URL) is injected. The Sogo
// secret key is intentionally never read here — it does not exist
// anywhere in this module. See backend/.env for that.
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) load(f.inputStream())
}

fun cfg(key: String): String =
    (localProps.getProperty(key) ?: project.findProperty(key) as String? ?: "")

